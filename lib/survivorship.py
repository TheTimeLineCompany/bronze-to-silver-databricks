"""Shared masters fed by several sources: per-source staging + one survivorship-aware master build.

Why: when two sources both load slv_mst_part directly, whichever runs last overwrites the other.
So no source notebook writes a shared master. Instead:

  1. Each source notebook loads its view of the master into its OWN staging table
         slv_stg_<master without 'slv_'>_<source code>      e.g. slv_stg_mst_part_s03
     (current state per business key; `_src_id` and `_src_changed_ts` record where and when).
  2. One master build per entity (masters/<master table>/nb_build_<master table>.py, generated by
     tools/p5_4_gen_master_build.py) reads all staging tables of that entity, applies the
     survivorship rules from registry/key_normalisation.yaml (approved at CP3b), and loads the master
     with its normal load pattern (scd2 or merge). It also seeds the unknown member and runs the QA checks.

Survivorship rules per attribute (registry/key_normalisation.yaml -> survivorship.<Entity>):
    priority: [S03_part_catalogue, S01_buyer_master]   first source in the list with a non-NULL value wins
    rule: most_recent_update                           the non-NULL value with the latest _src_changed_ts wins
Entity `default` applies to attributes without their own rule. Ties: entity `source_priority`, then source id.
Each master row records the winning source of every attribute in `_survivor` ("description=S03_part_catalogue;...").
"""
from __future__ import annotations

import os

import yaml

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCD_COLS = ("effective_to", "is_current")
AUDIT = ("_src_system", "_src_table", "_ingest_ts", "_load_ts", "_batch_id")


def source_code(source_id: str) -> str:
    return str(source_id).split("_")[0].lower()


def staging_table(master_table: str, source_id: str) -> str:
    base = master_table[4:] if master_table.startswith("slv_") else master_table
    return f"slv_stg_{base}_{source_code(source_id)}"


def staging_spec(t: dict) -> dict:
    """STTM table spec for the per-source staging table of a master: current state per business key,
    no surrogate key, no SCD columns (the master build adds them)."""
    sk = (t.get("surrogate_key") or {}).get("column")
    cols = [c for c in t["columns"] if c["target"] not in SCD_COLS and c["target"] != sk]
    return {**t, "target_kind": "staging", "load_pattern": "merge", "scd_type": None, "surrogate_key": None,
            "primary_key": list(t["business_key"]),
            "columns": [{**c, "key_role": ("BK" if c["target"] in t["business_key"] else ("none" if c.get("key_role") in ("PK", "PK_FK") else c.get("key_role")))}
                        for c in cols]}


def rules(entity: str, path: str | None = None) -> dict:
    path = path or os.path.join(_ROOT, "registry", "key_normalisation.yaml")
    with open(path, encoding="utf-8") as f:
        return ((yaml.safe_load(f) or {}).get("survivorship") or {}).get(entity) or {}


def feeding_sttms(entity: str, root: str | None = None) -> dict:
    """{source_id: sttm table} for every STTM that maps this conformed entity."""
    import glob
    root = root or _ROOT
    out = {}
    for p in sorted(glob.glob(os.path.join(root, "sources", "*", "04_mapping", "sttm.yaml"))):
        with open(p, encoding="utf-8") as f:
            doc = yaml.safe_load(f) or {}
        for t in doc.get("tables", []):
            if t.get("conformed_entity") == entity:
                out[doc["source_id"]] = t
    return out


def master_spec(entity_row: dict, sttm_tables: list) -> dict:
    """One spec for the master: registry metadata + the union of the columns every feeding STTM maps."""
    base = dict(sttm_tables[0])
    cols, seen = [], set()
    for t in sttm_tables:
        for c in t["columns"]:
            if c["target"] not in seen:
                seen.add(c["target"])
                cols.append(c)
    return {**base, "target_table": entity_row["target_table"], "business_key": list(entity_row["business_key"]),
            "target_kind": "master", "columns": cols}


def load_staging(spark, df, fqn, t, source_id, batch_id=None, src_system="", src_table=""):
    """Write one source's view of a master into its staging table (MERGE on the business key)."""
    from pyspark.sql import functions as F
    from lib.load_patterns import add_audit_columns, merge
    from datetime import datetime, timezone
    spec = staging_spec(t)
    keep = [c["target"] for c in spec["columns"] if c["target"] in df.columns]
    changed = F.col("effective_from") if "effective_from" in df.columns else F.current_timestamp()
    out = df.withColumn("_src_changed_ts", changed).select(*keep, "_src_changed_ts").withColumn("_src_id", F.lit(source_id))
    out = add_audit_columns(out, src_system, src_table, batch_id or datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S"))
    merge(spark, out, fqn, spec)
    return fqn


def survive(staged, business_key: list, attributes: list, entity_rules: dict):
    """Pure DataFrame logic: one row per business key from all staging rows (testable without Delta).

    staged: union of staging tables; columns = business key + attributes + _src_id + _src_changed_ts.
    Returns business key + attributes + effective_from (latest change of any contributing row) + _survivor.
    """
    from pyspark.sql import functions as F
    default = entity_rules.get("default", "most_recent_update")
    src_prio = entity_rules.get("source_priority") or []
    attr_rules = entity_rules.get("attributes") or {}

    def rank_expr(prio):
        r = F.lit(len(prio))
        for i, s in reversed(list(enumerate(prio))):
            r = F.when(F.col("_src_id") == s, F.lit(i)).otherwise(r)
        return r

    ts = F.coalesce(F.col("_src_changed_ts").cast("long"), F.lit(0))
    aggs = []
    for a in attributes:
        ar = attr_rules.get(a) or {}
        prio = ar.get("priority")
        rule = "priority" if prio else ar.get("rule", default if default != "source_priority" else "priority")
        prio = prio or src_prio
        isnull = F.col(a).isNull().cast("int")
        if rule == "priority":
            order = [isnull, rank_expr(prio), -ts]
        elif rule == "most_recent_update":
            order = [isnull, -ts, rank_expr(src_prio)]
        else:
            raise ValueError(f"unknown survivorship rule '{rule}' for attribute {a}")
        s = F.struct(*[o.alias(f"o{i}") for i, o in enumerate(order)], F.col("_src_id").alias("src"), F.col(a).alias("v"))
        aggs.append(F.min(s).alias(f"__{a}"))
    g = staged.groupBy(*business_key).agg(*aggs, F.max("_src_changed_ts").alias("effective_from"))
    sel = [F.col(k) for k in business_key] + [F.col(f"__{a}.v").alias(a) for a in attributes] + [F.col("effective_from")]
    surv = F.concat_ws(";", *[F.when(F.col(f"__{a}.v").isNotNull(), F.concat(F.lit(a + "="), F.col(f"__{a}.src"))) for a in attributes]) \
        if attributes else F.lit("")
    return g.select(*sel, surv.alias("_survivor"))


def build_master(spark, entity: str, catalog: str, schema: str, feeding: dict, batch_id=None, root: str | None = None):
    """Build one shared master from all its staging tables.

    feeding: {source_id: sttm_table_dict} for every STTM that maps this entity.
    """
    from functools import reduce
    from pyspark.sql import functions as F
    from lib.load_patterns import load
    root = root or _ROOT
    with open(os.path.join(root, "registry", "entities.yaml"), encoding="utf-8") as f:
        ent = next(e for e in yaml.safe_load(f)["entities"] if e["name"] == entity)
    spec = master_spec(ent, list(feeding.values()))
    sk = (spec.get("surrogate_key") or {}).get("column")
    bk = spec["business_key"]
    attrs = [c["target"] for c in spec["columns"] if c["target"] not in set(bk) | {sk, "effective_from", *SCD_COLS} and not c["target"].startswith("_")]
    frames = []
    for sid in feeding:
        fqn = f"{catalog}.{schema}.{staging_table(ent['target_table'], sid)}"
        df = spark.table(fqn)
        for a in attrs:
            if a not in df.columns:
                df = df.withColumn(a, F.lit(None))
        frames.append(df.select(*bk, *attrs, "_src_id", "_src_changed_ts"))
    staged = reduce(lambda x, y: x.unionByName(y), frames)
    m = survive(staged, bk, attrs, rules(entity, os.path.join(root, "registry", "key_normalisation.yaml")))
    if sk:
        of = (spec.get("surrogate_key") or {}).get("of") or bk
        m = m.withColumn(sk, F.sha2(F.concat_ws("|", *[F.col(c).cast("string") for c in of]), 256))
    if "effective_from" not in {c["target"] for c in spec["columns"]}:
        m = m.drop("effective_from")                     # merge-pattern masters keep no validity column
    target = f"{catalog}.{schema}.{ent['target_table']}"
    expected = m.select(*bk).distinct().count()          # QA-01 for the master: one current row per business key
    load(spark, m, target, spec, batch_id=batch_id, src_system="conformed", src_table=",".join(feeding))
    return target, spec, expected
